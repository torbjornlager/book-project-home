const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
global.window = global;
global.ELK = require('../vendor/elk.bundled.js');
global.document = {createElement: () => ({getContext: () => ({measureText: text => ({width: text.length * 7})})})};
vm.runInThisContext(fs.readFileSync(path.join(__dirname, '../js/sxml-diagram.js'), 'utf8'));
const dm = {key: '#root/datamodel0', body: ':- dynamic int/1.'};
const child = {id:'init', key:'init', kind:'state', children:[], initial:'', datamodels:[], spawns:[], onentry:[], onexit:[], defers:[], transitions:[]};
const root = {...child, id:'', key:'#root', kind:'statechart', children:[child], initial:'init', datamodels:[dm]};
const model = {root, nodes:[root, child], byId:new Map([['init',child]]), nested:new Map(), transitions:[], layout:null};
const fake = {model, liveDatamodels:new Map(), calls:0, setModel(m, options) {assert.equal(m, model); assert(options.preserveViewport); this.calls++; return Promise.resolve();}, _paint() {}};
(async () => {
  const original = dm.body;
  await SXMLDiagram.Diagram.prototype.setDatamodelFacts.call(fake, [{key:dm.key, facts:['int(5).','int(5).'], truncated:false}]);
  await SXMLDiagram.Diagram.prototype.setDatamodelFacts.call(fake, [{key:dm.key, facts:['int(5).','int(5).','int(5).'], truncated:false}]);
  assert.deepEqual(fake.liveDatamodels.get(dm.key).changed, [false,false,true]);
  const base = await SXMLDiagram.layout(model, 'RIGHT');
  const geo = await SXMLDiagram.layout(model, 'RIGHT', {'studio.liveDatamodels':fake.liveDatamodels});
  assert(geo.boxes.get(dm.key).h > base.boxes.get(dm.key).h);
  assert.deepEqual(geo.info.get(dm.key).lines, ['int(5).','','int(5).','','int(5).']);
  assert.deepEqual(geo.info.get(dm.key).changedLines, [false,false,false,false,true], 'Only the new clause is highlighted; separators remain unhighlighted.');
  assert.equal(geo.info.get(dm.key).fullText, 'int(5).\n\nint(5).\n\nint(5).');
  assert(!geo.info.get(dm.key).fullText.includes(dm.body));
  await SXMLDiagram.Diagram.prototype.setDatamodelFacts.call(fake, [{key:dm.key, facts:['value(1).', 'summary(A,B) :-\n    shared_fact(A),\n    local_label(B).'], truncated:false}]);
  const ruleGeo = await SXMLDiagram.layout(model, 'RIGHT', {'studio.liveDatamodels':fake.liveDatamodels});
  assert(ruleGeo.info.get(dm.key).lines.includes('    shared_fact(A),'));
  assert(ruleGeo.info.get(dm.key).lines.includes('    local_label(B).'));
  // The 48-line preview applies to source and runtime notes, while hover retains everything.
  const sourceLines = Array.from({length: 48}, (_, i) => 'source_fact(' + i + ').');
  dm.body = sourceLines.join('\n');
  const sourcePreview = await SXMLDiagram.layout(model, 'RIGHT');
  assert.deepEqual(sourcePreview.info.get(dm.key).lines, sourceLines);
  dm.body += '\nsource_fact(48).';
  const overflow = await SXMLDiagram.layout(model, 'RIGHT');
  assert.deepEqual(overflow.info.get(dm.key).lines, [...sourceLines, '… more clauses (hover to view)']);
  assert(overflow.info.get(dm.key).fullText.endsWith('source_fact(48).'));
  dm.body = original;
  const facts = Array.from({length: 25}, (_, i) => 'value(' + i + ').');
  await SXMLDiagram.Diagram.prototype.setDatamodelFacts.call(fake, [{key:dm.key, facts, truncated:false}]);
  const runtimePreview = (await SXMLDiagram.layout(model, 'RIGHT', {'studio.liveDatamodels':fake.liveDatamodels})).info.get(dm.key);
  assert.equal(runtimePreview.lines.length, 49);
  assert.equal(runtimePreview.lines[46], 'value(23).');
  assert.equal(runtimePreview.lines[47], '');
  assert.equal(runtimePreview.lines[48], '… more clauses (hover to view)');
  assert.equal(runtimePreview.fullText, facts.join('\n\n'));
  assert.equal(dm.body, original);
  const app = fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8');
  const helpers = app.slice(app.indexOf('function splitTop('), app.indexOf('function firedTransition('));
  const playback = app.slice(app.indexOf('function play(item)'), app.indexOf('/* ---------- side panel, files, chrome ---------- */'));
  const received = [];
  const context = {window: {}, model, diagram:{setDatamodelFacts(updates) {received.push(updates); return Promise.resolve();}}, console};
  vm.createContext(context); vm.runInContext(helpers + playback, context);
  assert(context.play({type:'trace', text:"datamodel_snapshot([init],[data('#root',['int(30).','label(\\'a,b\\').'],false)])"}));
  assert.equal(received[0][0].facts[1], "label('a,b').");
  assert.equal(received[0][0].key, dm.key);
  assert(!context.play({type:'trace', text:"datamodel_snapshot([another_chart],[data('#root',['int(9).'],false)])"}));
  SXMLDiagram.Diagram.prototype.setRun.call(fake, false);
  assert.equal(fake.liveDatamodels.size, 0);
  assert.equal(dm.body, original);
  console.log('Checked snapshot parsing and chart identity, duplicate-fact changes/highlights, blank clause separators, 48-line previews/overflow, source preservation and clearing on stop.');
})().catch(error => {console.error(error); process.exitCode=1;});
