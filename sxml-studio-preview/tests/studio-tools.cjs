const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
vm.runInThisContext(fs.readFileSync(require('node:path').join(__dirname, '../js/studio-model.js'), 'utf8'));
const tools = SXMLStudio;
const root = {key:'#root', initial:'a', depth:0, transitions:[]};
const a = {key:'a', id:'a', parent:root, depth:1, transitions:[]};
const b = {key:'b', id:'b', parent:a, depth:2, transitions:[]};
a.transitions.push({key:'a/go0',on:'cancel',to:['c'],source:a});
b.transitions.push({key:'b/go0',on:'finish(X)',to:['c'],source:b});
const c = {key:'c', id:'c', parent:root, depth:1, transitions:[]};
const model = {root, byId:new Map([['a',a],['b',b],['c',c]])};
assert.deepEqual(tools.candidates(model,['a','b']).map(t=>t.on), ['finish(X)','cancel'], 'Discover child handlers before ancestors, without duplicates.');
a.transitions.push({key:'a/go1',on:'loop',to:['a'],source:a});
assert.equal(tools.paths(model,6,40).length,2,'Cycles must not expand forever.');
assert.equal(tools.paths(model,6,1).length,1);
assert(tools.validScenario({name:'scenario',steps:[{event:'go(1)',states:['a'],facts:[{owner:'#root',clause:'value(1).'}]}]}));
assert(!tools.validScenario({name:'bad',steps:[{event:4}]}));
assert(!tools.validScenario({name:'bad',steps:new Array(201).fill({event:'go'})}));
assert.deepEqual(tools.assertions({states:['a'],facts:[{owner:'#root',clause:'value(1).'}]}, {active:['a'],facts:[{owner:'#root',facts:['value(1).']}]}), []);
assert.equal(tools.assertions({states:['b'],facts:[{owner:'other',clause:'value(1).'}]}, {active:['a'],facts:[]}).length,2);
assert.equal(tools.assertions({facts:[{owner:'#root',clause:'value(1).'}]}, {active:[],facts:[{owner:'#root',scope:'child/spawn0',facts:['value(1).']}]}).length,1,'Nested facts must never satisfy a parent assertion.');
const doc = {childNodes:[],createComment(data) {return {nodeType:8,data};},appendChild(n){this.childNodes.push(n);}};
const meta = {descriptions:{a:'two--hyphens <tag>'},notes:['Text --> XML'],scenarios:[{name:'valid',steps:[]}]};
tools.setMetadata(doc,meta);
assert(!doc.childNodes[0].data.includes('--'));
assert.deepEqual(tools.metadata(doc),meta);
tools.setMetadata(doc,{...meta, notes:['updated']});
assert.equal(doc.childNodes.length,1);
assert.deepEqual(tools.metadata(doc).notes,['updated']);
console.log('Checked inherited event discovery, cycle/path bounds, assertions, scenario validation and safe metadata round trips.');
